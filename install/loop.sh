#!/usr/bin/env bash
#
# CT vault-loop installer: Docker + n8n. Runs INSIDE the container; from the
# Proxmox host use proxmox/create-lxc.sh or proxmox/update-lxc.sh, which push
# and run it.
#
# Re-running this IS the update path. It never overwrites an existing value in
# .env except N8N_VERSION, which it sets to the pin below. To upgrade n8n, bump
# N8N_VERSION_PIN (an exact release at least two weeks old) and re-run.
#
# Environment overrides:
#   LOOP_DIR   install location (default /opt/vault-loop)
#   N8N_PORT   host port        (default 5678)

set -euo pipefail

N8N_VERSION_PIN="2.46.6"
DIR="${LOOP_DIR:-/opt/vault-loop}"
PORT="${N8N_PORT:-5678}"

say()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m warn\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m fail\033[0m %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "run as root"
[[ "$PORT" =~ ^[0-9]+$ ]] || die "N8N_PORT must be a number"

# --- 1. Docker ---------------------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
  say "Installing Docker from the official repository..."
  apt-get update -qq
  apt-get install -y -qq ca-certificates curl openssl
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/debian/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/debian $(. /etc/os-release && echo "$VERSION_CODENAME") stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -qq
  apt-get install -y -qq docker-ce docker-ce-cli containerd.io docker-compose-plugin
  systemctl enable --now docker
else
  say "Docker already present: $(docker --version)"
fi
docker info >/dev/null 2>&1 || die "Docker is installed but not working. In an LXC this is almost always missing features: on the host, pct set <CTID> --features nesting=1,keyctl=1 && pct reboot <CTID>"

# --- 2. .env -----------------------------------------------------------------
mkdir -p "$DIR"
cd "$DIR"
if [ ! -f .env ]; then
  ( umask 077; : > .env )
fi
chmod 600 .env

get_kv() { grep -E "^$1=" .env | tail -1 | cut -d= -f2- || true; }
set_kv() {
  if grep -qE "^$1=" .env; then
    sed -i "s|^$1=.*|$1=$2|" .env
  else
    printf '%s=%s\n' "$1" "$2" >> .env
  fi
}
# Only fills a key that is missing: secrets and your own edits survive re-runs.
default_kv() { [ -n "$(get_kv "$1")" ] || set_kv "$1" "$2"; }

IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
TZ_NAME="$(cat /etc/timezone 2>/dev/null || true)"
[ -n "$TZ_NAME" ] || TZ_NAME="$(timedatectl show -p Timezone --value 2>/dev/null || true)"
[ -n "$TZ_NAME" ] || TZ_NAME="UTC"

set_kv     N8N_VERSION "$N8N_VERSION_PIN"
default_kv HOST_PORT "$PORT"
default_kv N8N_ENCRYPTION_KEY "$(openssl rand -hex 32)"
default_kv GENERIC_TIMEZONE "$TZ_NAME"
default_kv TZ "$TZ_NAME"
default_kv N8N_HOST "${IP:-localhost}"
default_kv N8N_PROTOCOL http
default_kv WEBHOOK_URL "http://${IP:-localhost}:${PORT}/"
# Plain http on the LAN / tailnet in Phase 0. n8n refuses to log in over http
# with secure cookies on, so they are off. Turn this back to true if n8n is
# ever served on an https hostname.
default_kv N8N_SECURE_COOKIE false
default_kv N8N_METRICS true
default_kv N8N_METRICS_INCLUDE_DEFAULT_METRICS true
default_kv N8N_DIAGNOSTICS_ENABLED false
default_kv N8N_VERSION_NOTIFICATIONS_ENABLED false
default_kv N8N_PERSONALIZATION_ENABLED false
default_kv EXECUTIONS_DATA_PRUNE true
default_kv EXECUTIONS_DATA_MAX_AGE 336

LOG_DRIVER="json-file"
if systemctl is-active --quiet systemd-journald 2>/dev/null; then
  LOG_DRIVER="journald"   # journald -> rsyslog -> VictoriaLogs, like the other services
fi

# --- 3. Compose file (generated; edit this script, not the file) ------------
cat > docker-compose.yml <<EOF
# Generated by vault-loop install/loop.sh -- edits here are overwritten.
services:
  n8n:
    image: docker.n8n.io/n8nio/n8n:\${N8N_VERSION}
    restart: unless-stopped
    env_file: .env
    ports:
      - "\${HOST_PORT}:5678"
    volumes:
      - n8n_data:/home/node/.n8n
    logging:
      driver: ${LOG_DRIVER}
volumes:
  n8n_data:
EOF

# --- 4. Start ----------------------------------------------------------------
say "Pulling n8n ${N8N_VERSION_PIN}..."
docker compose pull -q
docker compose up -d --remove-orphans

HOST_PORT="$(get_kv HOST_PORT)"
# /healthz answers while n8n is still starting (and /metrics then serves a
# "starting up" HTML page), so wait for readiness: about 40 s on a first start.
say "Waiting for n8n on :${HOST_PORT}..."
ok=0
for _ in $(seq 1 90); do
  if curl -fsS -m 3 "http://127.0.0.1:${HOST_PORT}/healthz/readiness" >/dev/null 2>&1; then ok=1; break; fi
  sleep 2
done
[ "$ok" = "1" ] || die "n8n was not ready within 3 minutes. Check: docker compose -f $DIR/docker-compose.yml logs n8n"

if curl -fsS -m 5 "http://127.0.0.1:${HOST_PORT}/metrics" 2>/dev/null | grep -q '^n8n_'; then
  METRICS="ok"
else
  METRICS="not answering -- check N8N_METRICS in $DIR/.env"
  warn "/metrics is $METRICS"
fi

cat <<EOF

  n8n ${N8N_VERSION_PIN} is running.

  Open         http://${IP:-<this-host>}:${HOST_PORT}   (create the owner account on first visit)
  Metrics      http://${IP:-<this-host>}:${HOST_PORT}/metrics  (${METRICS})
  Config       $DIR/.env   (secrets live here; never paste it anywhere)
  Logs         docker compose -f $DIR/docker-compose.yml logs -f n8n
  Update       bump N8N_VERSION_PIN in install/loop.sh, then proxmox/update-lxc.sh

  Register metrics on both mon LXCs (from each Proxmox host, homelab-monitoring repo):
    ./scripts/register-service.sh --ctid 200 --service vault-loop --target ${IP:-<this-host>}:${HOST_PORT} --yes
    ./scripts/register-service.sh --ctid 201 --service vault-loop --target ${IP:-<this-host>}:${HOST_PORT} --yes

  Back up the encryption key somewhere safe: without it, credentials saved in
  n8n cannot be decrypted after a rebuild.  grep N8N_ENCRYPTION_KEY $DIR/.env

EOF
